def claim(cid, label, stage, aliases, law_hints, fields, elements, summary,
          as_of="dismiss_date", matter="labor", priority=50):
    """fields: list of (key, critical, priority[, why[, basis]]) or dict overrides."""
    flds = []
    for item in fields:
        if isinstance(item, dict):
            d = dict(item)
        else:
            key, critical, prio = item[0], item[1], item[2]
            d = {"key": key, "critical": critical, "priority": prio}
            if len(item) > 3 and item[3]:
                d["why"] = item[3]
            if len(item) > 4 and item[4]:
                d["basis"] = item[4]
        flds.append(d)
    return cid, {
        "label": label, "matter": matter, "stage": stage, "aliases": aliases,
        "law_hints": law_hints, "default_as_of": as_of, "summary": summary,
        "priority": priority, "fields": flds, "elements": elements,
    }


def el(eid, label, facts, essential=True, requires=None, why="", proof=None):
    d = {"id": eid, "label": label, "facts": facts, "essential": essential}
    if requires:
        d["requires"] = requires
    if why:
        d["why"] = why
    if proof:
        d["proof"] = proof
    return d


