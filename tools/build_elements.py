"""Build the fact catalog and claim/element schemas.

Why a builder instead of hand-editing JSON
------------------------------------------
The previous schema hard-coded one flat questionnaire per cause of action, and
the agent silently fell back to ``labor_dismissal`` for anything it did not
recognise.  This builder makes the structure explicit:

* ``facts``  — a shared catalog of facts (one question per fact, deduplicated);
* ``claims`` — labour claims that reference facts and organise them into a
  hierarchy of *elements* (claim -> element -> fact -> proof).

A fact can be critical in one claim and optional in another; a claim can put a
fact inside a conditional element so the question disappears when the branch
does not apply.  The generated JSON is what the runtime loads.

Usage:
    python3 tools/build_elements.py
"""
